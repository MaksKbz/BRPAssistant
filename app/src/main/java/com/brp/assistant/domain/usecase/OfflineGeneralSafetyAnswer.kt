package com.brp.assistant.domain.usecase

/** Deterministic offline answers for high-risk everyday outdoor questions. */
object OfflineGeneralSafetyAnswer {
    private val fireWords = listOf("огонь", "костер", "костёр", "разжечь", "развести огонь", "топор", "дров")

    fun answerFor(question: String): String? {
        val normalized = question.lowercase()
        if (fireWords.none { normalized.contains(it) }) return null
        return """Безопасный вариант — использовать только разрешённое место для костра или туристическую горелку.

1. Проверьте местные правила и запрет на открытый огонь. В сухом лесу, при сильном ветре или рядом с торфом огонь не разводите.
2. Не разводите огонь на гидроцикле, рядом с ним, на причале, возле топлива или сухой растительности. Для Sea-Doo используйте только штатное топливо и держите огонь полностью отдельно от техники.
3. Если костёр разрешён, выбирайте оборудованное место, очистите круг до грунта, держите рядом воду и лопату и не оставляйте огонь без присмотра.
4. Перед уходом полностью залейте угли водой, перемешайте и убедитесь, что всё холодное. Не закапывайте тлеющие угли.
5. При распространении огня сразу отойдите против ветра, предупредите людей и звоните в экстренную службу. Не рискуйте техникой и жизнью ради тушения большого огня."""
    }
}
